/// حالة تقدم الحج (في الذاكرة أثناء تشغيل التطبيق)
class HajjStore extends ChangeNotifier {
  HajjStore._();
  static final HajjStore I = HajjStore._();

  int step = 0;
  final Set<int> done = {};

  void go(int i) {
    step = i.clamp(0, 7).toInt();
    notifyListeners();
  }

  void complete() {
    done.add(step);
    if (step < 7) step++;
    notifyListeners();
  }

  void reset() {
    done.clear();
    step = 0;
    notifyListeners();
  }
}

