/// زخرفة إسلامية هندسية (نجوم ثمانية)
class UPatternPainter extends CustomPainter {
  final double opacity;
  const UPatternPainter({this.opacity = .07});

  @override
  void paint(Canvas canvas, Size size) {
    final paint = Paint()
      ..style = PaintingStyle.stroke
      ..strokeWidth = 1
      ..color = Colors.white.withOpacity(opacity);
    const step = 58.0;
    const r = 22.0;
    for (double y = -10; y < size.height + step; y += step) {
      for (double x = -10; x < size.width + step; x += step) {
        canvas.drawPath(_star(Offset(x, y), r), paint);
        canvas.drawPath(_star(Offset(x + step / 2, y + step / 2), r * .55), paint);
      }
    }
  }

  Path _star(Offset c, double r) {
    final path = Path();
    for (final rot in [math.pi / 4, 0.0]) {
      for (int i = 0; i < 4; i++) {
        final a = rot + i * math.pi / 2 + math.pi / 4;
        final pt = Offset(c.dx + r * math.cos(a), c.dy + r * math.sin(a));
        i == 0 ? path.moveTo(pt.dx, pt.dy) : path.lineTo(pt.dx, pt.dy);
      }
      path.close();
    }
    return path;
  }

  @override
  bool shouldRepaint(covariant UPatternPainter old) => old.opacity != opacity;
}

/// بطاقة بيضاء بإطار ناعم
class UCard extends StatelessWidget {
  final Widget child;
  final EdgeInsets padding;
  final Color? color;
  const UCard(
      {super.key,
      required this.child,
      this.padding = const EdgeInsets.all(16),
      this.color});

  @override
  Widget build(BuildContext context) => Container(
        width: double.infinity,
        padding: padding,
        decoration: BoxDecoration(
          color: color ?? Colors.white,
          borderRadius: BorderRadius.circular(24),
          border: Border.all(color: UC.border),
          boxShadow: [
            BoxShadow(
              color: const Color(0xFF0F5E45).withOpacity(.07),
              blurRadius: 18,
              offset: const Offset(0, 8),
            ),
          ],
        ),
        child: child,
      );
}

