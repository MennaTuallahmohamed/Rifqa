class HPin {
  final String id, kind, emoji, label;
  final Offset pos;
  const HPin(this.id, this.kind, this.emoji, this.label, this.pos);
}

const hPinKinds = <List<String>>[
  ['meet', '🚩', 'نقطة تجمع الحملة'],
  ['family', '👪', 'مكان العائلة'],
  ['shoes', '👟', 'مكان حذائي'],
  ['hotel', '🏨', 'مخرج الفندق'],
];

class HaramainStore extends ChangeNotifier {
  HaramainStore._();
  static final HaramainStore I = HaramainStore._();

  final Map<int, Offset?> me = {0: null, 1: null};
  final Map<int, List<HPin>> pins = {0: [], 1: []};
  int tawaf = 0, sai = 0, ziyara = 0;

  void setMe(int h, Offset p) {
    me[h] = p;
    notifyListeners();
  }

  void clearMe(int h) {
    me[h] = null;
    notifyListeners();
  }

  void addPin(int h, String kind, Offset p) {
    final k = hPinKinds.firstWhere((e) => e[0] == kind);
    // كل نوع له مثبّت واحد فقط
    pins[h]!.removeWhere((e) => e.kind == kind);
    pins[h]!.add(HPin('${kind}_${DateTime.now().microsecondsSinceEpoch}', kind, k[1], k[2], p));
    notifyListeners();
  }

  void removePin(int h, String id) {
    pins[h]!.removeWhere((e) => e.id == id);
    notifyListeners();
  }

  void setTawaf(int v) {
    tawaf = v.clamp(0, 7).toInt();
    notifyListeners();
  }

  void setSai(int v) {
    sai = v.clamp(0, 7).toInt();
    notifyListeners();
  }

  void setZiyara(int v) {
    ziyara = v;
    notifyListeners();
  }
}
