class HPoi {
  final String id, emoji, name, desc, say;
  final HCat cat;
  final double x, y;
  final bool exact;
  const HPoi(this.id, this.cat, this.emoji, this.name, this.x, this.y,
      this.desc, this.say,
      {this.exact = false});
  Offset get pos => Offset(x, y);
}

class HTip {
  final String emoji, title, text;
  const HTip(this.emoji, this.title, this.text);
}

class HHaram {
  final String id, name, subtitle;
  final double mpu; // متر لكل وحدة خريطة (تقريبي)
  final List<HPoi> pois;
  final List<String> tourIds;
  final List<HTip> tips;
  final List<HTip> nearby;
  final Offset startMe; // موضع افتراضي مقترح
  const HHaram(this.id, this.name, this.subtitle, this.mpu, this.pois,
      this.tourIds, this.tips, this.nearby, this.startMe);
}

